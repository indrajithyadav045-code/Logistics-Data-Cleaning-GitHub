def _build_simulation_framework(doc) -> None:
    _add_heading(doc, "Simulation Conceptual Framework", 1)
    _add_para(doc,
        "The simulation implements a discrete-time model where the state of the warehouse "
        "is updated once per simulated day. The simulation clock advances in integer steps.\n\n"
        "Daily event sequence (within each simulated day):\n"
        "1. Receive replenishments: orders with today's arrival day are added to on-hand.\n"
        "2. Sample demand: draw from the calibrated demand model.\n"
        "3. Fulfil demand: fulfilled = min(demand, on_hand).\n"
        "4. Lost sales: shortfall = demand − fulfilled (units permanently lost).\n"
        "5. Update state: on_hand = on_hand − fulfilled.\n"
        "6. Check disruption: Bernoulli draw for supplier disruption event.\n"
        "7. Reorder decision: if inv_position ≤ s and no disruption, place order Q.\n"
        "8. Accumulate costs and performance metrics.\n\n"
        "The lost-sales model is chosen over backorders because Brazilian e-commerce "
        "customers facing stockouts will purchase from a competitor, making demand "
        "effectively lost rather than deferred."
    )


