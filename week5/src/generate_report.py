def _build_limitations(doc) -> None:
    _add_heading(doc, "Limitations", 1)
    _add_para(doc,
        "1. The Olist dataset represents historical orders, not warehouse inventory records. "
        "   Unit costs, lead times and disruption probabilities are simulation assumptions.\n\n"
        "2. The simulation models a single product/SKU aggregate. Real warehouses manage "
        "   thousands of SKUs with heterogeneous demand and supply characteristics.\n\n"
        "3. The demand bootstrap model cannot generate demand values outside the "
        "   historical range. Future demand levels (e.g., after platform growth) "
        "   may exceed the observed maximum.\n\n"
        "4. Lost-sales are assumed (not backorders). If some customers do wait, "
        "   the shortage penalty is overestimated.\n\n"
        "5. The grid search covers a finite parameter space; a continuous optimisation "
        "   (e.g., stochastic gradient descent) might identify a better solution.\n\n"
        "6. The simulation does not model multiple warehouses, distribution networks "
        "   or supplier capacity constraints."
    )


