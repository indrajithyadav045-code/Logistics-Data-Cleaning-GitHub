def _add_heading(doc: "Document", text: str, level: int) -> None:
    doc.add_heading(text, level=level)


def _add_para(doc: "Document", text: str, bold: bool = False) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold


def _add_table_from_df(
    doc: "Document",
    df: pd.DataFrame,
    title: Optional[str] = None,
    num_fmt: Optional[dict] = None,
) -> None:
    """Insert a DataFrame as a Word table with header row."""
    if title:
        doc.add_paragraph(title, style="Intense Quote")

    table = doc.add_table(rows=1, cols=len(df.columns))
    table.style = "Table Grid"

    # Header row
    hdr = table.rows[0].cells
    for i, col in enumerate(df.columns):
        hdr[i].text = str(col)
        hdr[i].paragraphs[0].runs[0].bold = True

    # Data rows
    for _, row in df.iterrows():
        cells = table.add_row().cells
        for i, val in enumerate(row):
            if num_fmt and df.columns[i] in num_fmt:
                cells[i].text = num_fmt[df.columns[i]].format(val)
            elif isinstance(val, float):
                cells[i].text = f"{val:,.4f}" if abs(val) < 10 else f"{val:,.1f}"
            else:
                cells[i].text = str(val)
    doc.add_paragraph()


def _add_figure(
    doc: "Document",
    image_path: Path,
    caption: str,
    width_inches: float = 6.0,
) -> None:
    """Insert an image with a caption."""
    if image_path.exists():
        doc.add_picture(str(image_path), width=Inches(width_inches))
        p = doc.add_paragraph(f"Figure: {caption}")
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.runs[0].italic = True
        p.runs[0].font.size = Pt(9)
    else:
        doc.add_paragraph(f"[Figure not available: {image_path.name}]")
    doc.add_paragraph()


