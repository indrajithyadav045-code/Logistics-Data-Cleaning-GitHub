def generate_report(
    demand_stats: dict,
    summary_df: pd.DataFrame,
    pairwise_df: pd.DataFrame,
    plot_paths: dict,
) -> Path:
    """Build and save the complete DOCX report.

    Parameters
    ----------
    demand_stats  : dataset statistics dict
    summary_df    : scenario summary DataFrame
    pairwise_df   : pairwise t-test DataFrame
    plot_paths    : dict mapping chart key → Path

    Returns
    -------
    Path to the saved .docx file.
    """
    if not DOCX_AVAILABLE:
        print("[generate_report] python-docx not available. Skipping DOCX generation.")
        return REPORTS_DIR / "Week5_Logistics_Simulation_Report.docx"

    print("\n=== GENERATING DOCX REPORT ===")
    doc = Document()

    # Page margins
    for section in doc.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1.2)
        section.right_margin = Inches(1.2)

    _build_title_page(doc, demand_stats)
    _build_executive_summary(doc, demand_stats, summary_df)
    _build_introduction(doc)
    _build_problem_statement(doc)
    _build_objectives(doc)
    _build_dataset_description(doc, demand_stats)
    _build_data_preparation(doc)
    _build_simulation_framework(doc)
    _build_assumptions(doc)
    _build_mathematical_model(doc)
    _build_demand_modeling(doc, plot_paths)
    _build_replenishment_policy(doc)
    _build_scenario_design(doc, summary_df)

    _add_heading(doc, "Python Implementation", 1)
    _add_para(doc,
        "The simulation is implemented in Python 3.11 using a modular architecture:\n"
        "• simulation_config.py: single source of truth for all parameters.\n"
        "• inventory_policy.py: PolicyParameters dataclass + InventoryPolicy class.\n"
        "• simulation_engine.py: DemandSampler, run_single_replication(), run_monte_carlo().\n"
        "• scenario_analysis.py: run_all_scenarios(), grid_search_optimisation().\n"
        "• statistical_analysis.py: descriptive_stats(), pairwise_ttest_vs_baseline().\n"
        "• visualization.py: generate_all_plots() producing 10 PNG charts.\n"
        "All modules use type hints, docstrings and input validation."
    )

    _build_experimental_setup(doc)
    _build_performance_metrics(doc)
    _build_results(doc, summary_df, pairwise_df, plot_paths)
    _build_visualization_chapter(doc, plot_paths)

    _add_heading(doc, "Comparative Scenario Analysis", 1)
    _add_para(doc,
        "The six scenarios span the operational risk spectrum from low-risk baseline "
        "to high-disruption environments. Key comparative observations:\n\n"
        "• Cost vs service: the optimised policy dominates the baseline on both metrics.\n"
        "• Demand surge is the most financially damaging scenario (shortage cost spike).\n"
        "• Supplier disruptions produce the highest stockout frequency but moderate "
        "  shortage cost (because disruptions are intermittent and lead times otherwise normal).\n"
        "• Safety stock strategy is cost-effective when stockout penalties are high.\n"
        "• Extended supplier delays (S3) reduce fill rate moderately; the reorder point "
        "  should be recalibrated when lead times increase by more than 50%."
    )

    _build_recommendations(doc, summary_df)
    _build_limitations(doc)
    _build_future_improvements(doc)
    _build_conclusion(doc, summary_df)
    _build_references(doc)
    _build_appendix(doc)

    out_path = REPORTS_DIR / "Week5_Logistics_Simulation_Report.docx"
    doc.save(str(out_path))
    print(f"[generate_report] Report saved to {out_path}")
    return out_path
