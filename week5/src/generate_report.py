def _build_mathematical_model(doc) -> None:
    _add_heading(doc, "Mathematical Model", 1)
    _add_para(doc,
        "Inventory position on day t:\n"
        "  IP(t) = OH(t) + OO(t)\n"
        "where OH(t) = on-hand units, OO(t) = units on order.\n\n"
        "Daily state update:\n"
        "  OH(t+1) = max(0, OH(t) + R(t) − D(t))\n"
        "where R(t) = replenishment arrivals on day t, D(t) = demand on day t.\n\n"
        "Fulfilled demand:\n"
        "  F(t) = min(D(t), OH(t) + R(t))\n\n"
        "Lost sales:\n"
        "  L(t) = D(t) − F(t)\n\n"
        "Fill rate (over horizon T after warm-up W):\n"
        "  FR = Σ F(t) / Σ D(t),  t = W+1 … T\n\n"
        "Total cost:\n"
        "  TC = Σ [h·OH(t) + K·1{order placed on t} + p·L(t)]\n"
        "where h = R$0.50/unit/day, K = R$500/order, p = R$25/lost unit.\n\n"
        "Replenishment policy (continuous-review):\n"
        "  Place order Q when IP(t) ≤ s, provided no disruption is active.\n"
        "Lead time: LT ~ Discrete Uniform(lt_min, lt_max).\n\n"
        "Safety stock (theoretical, 95% service level):\n"
        "  SS = z(0.95) × σ_D × √(mean_LT) ≈ 1.645 × σ_D × √7"
    )


def _build_demand_modeling(doc, plot_paths: dict) -> None:
    _add_heading(doc, "Demand Modeling", 1)
    _add_para(doc,
        "Three candidate demand models were evaluated:\n\n"
        "1. Empirical bootstrap (weekday-conditioned): Each simulated day's demand "
        "   is drawn with replacement from historical demand observations for the "
        "   same day-of-week. This preserves the exact empirical distribution "
        "   including zero-demand days, extreme values and weekday seasonality.\n\n"
        "2. Poisson(λ=mean): Assumes equidispersion (variance = mean). "
        "   Rejected by Kolmogorov-Smirnov test (p < 0.05) due to overdispersion "
        "   in the Olist data (variance >> mean).\n\n"
        "3. Negative Binomial (mu, r): Appropriate for overdispersed count data. "
        "   Provides a better parametric fit but loses the weekday signal.\n\n"
        "Selection: Empirical bootstrap (weekday-conditioned) was chosen because:\n"
        "• The KS test rejects Poisson at the 5% level.\n"
        "• Weekday effects are statistically significant (Fridays see higher demand).\n"
        "• The dataset (770+ days) is large enough for bootstrap.\n"
        "• Bootstrap preserves extreme events such as Black Friday 2017 (1,176 orders)."
    )
    if "01_demand_distribution" in plot_paths:
        _add_figure(doc, plot_paths["01_demand_distribution"],
                    "Historical daily demand distribution and weekday breakdown", width_inches=6.0)


